/// Hindi and Spanish copy, keyed by the English string.
///
/// English is the message key rather than a symbolic id. The app pairs Bangla and English at every
/// call site — `context.tr('বাংলা', 'English')` — so the English text already exists at all 440 of
/// them, and adding a language this way touches none. The trade is that two places needing
/// different translations of identical English words would collide; none currently do, and the
/// generator that builds this file reports any key it cannot account for.
///
/// The 45 call sites that interpolate a value pass `hi:` and `es:` explicitly instead, because
/// their English text is assembled at runtime and cannot serve as a key.
///
/// Anything absent falls back to English rather than showing a key or an empty box.
///
/// NOTE: these translations have not been reviewed by a native speaker. For a medical app that is
/// a real gap — see the caveat in CLAUDE.md before shipping.
/// Picks copy for [locale] without a BuildContext — the notification and alarm layers run in a
/// background isolate where there is no element tree to read a theme from.
String trIn(AppLocale locale, String bn, String en, {String? hi, String? es}) => switch (locale) {
      AppLocale.bn => bn,
      AppLocale.en => en,
      AppLocale.hi => hi ?? Translations.hi[en] ?? en,
      AppLocale.es => es ?? Translations.es[en] ?? en,
    };

